import axios from 'axios'

// Single API base URL. Empty = same origin (FastAPI serves the site, or Vite proxies /api in dev).
// Override with VITE_API_URL=http://localhost:8000 if you serve the frontend elsewhere.
export const API_BASE = import.meta.env.VITE_API_URL || ''
const client = axios.create({ baseURL: API_BASE, timeout: 120000 })

// Maps any failure to a message that is safe and useful to show users.
function toMessage(err) {
  if (err.response) return err.response.data?.error || 'Unable to analyze this image. Please try another X-ray.'
  return 'Unable to connect to the AI server. Please check that it is running and try again.'
}

export async function getHealth() {
  const { data } = await client.get('/api/health')
  return data
}

export async function getModelInfo() {
  const { data } = await client.get('/api/model-info')
  return data
}

export async function predict(file) {
  const form = new FormData()
  form.append('file', file)
  try {
    const { data } = await client.post('/api/predict', form)
    return data
  } catch (err) {
    const e = new Error(toMessage(err))
    e.status = err.response?.status
    throw e
  }
}

// Returns a PDF Blob generated by the backend from the stored prediction.
export async function downloadReport(predictionId) {
  try {
    const { data } = await client.post('/api/report', { prediction_id: predictionId }, { responseType: 'blob' })
    return data
  } catch (err) {
    let msg = toMessage(err)
    if (err.response?.data instanceof Blob) {
      try { msg = JSON.parse(await err.response.data.text()).error || msg } catch { /* keep default */ }
    }
    throw new Error(msg)
  }
}

export const plotUrl = (name) => `${API_BASE}/api/evaluation-plot/${name}`
